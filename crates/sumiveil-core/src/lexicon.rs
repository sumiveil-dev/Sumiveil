/// `s` の先頭が一覧のどれかなら、その語 (長いものを優先)。
pub fn starts_with_any<'a>(s: &str, words: &[&'a str]) -> Option<&'a str> {
    words.iter().filter(|w| s.starts_with(**w)).max_by_key(|w| w.len()).copied()
}

/// `s` の末尾が一覧のどれかなら、その語 (長いものを優先)。
pub fn ends_with_any<'a>(s: &str, words: &[&'a str]) -> Option<&'a str> {
    words.iter().filter(|w| s.ends_with(**w)).max_by_key(|w| w.len()).copied()
}
